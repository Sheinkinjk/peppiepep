#!/usr/bin/env node
/**
 * Real publish and modification dates for every page, read from git.
 *
 * These were hand-set props, and they froze. Twenty-five pages shipped showing
 * "Last checked by Refer Labs, 19 August 2026" while being edited repeatedly
 * afterwards, several on the day this was written. Worse than stale: 19 August
 * is the day BEFORE those pages' first commit, so the site was asserting a
 * review that happened before the page existed.
 *
 * They also set datePublished and dateModified to the same value, so every page
 * told Google it was published and modified on the same day. For an edited page
 * that is wrong in both directions, and it means datePublished moves forward
 * every time the date is bumped, which reads as a brand-new page each time
 * rather than an established one accruing authority.
 *
 * So the dates are generated, never typed. `published` is the first commit that
 * added the page, `updated` the most recent commit that touched it. Both are
 * facts about the repository that no one has to remember to maintain.
 *
 * WHAT THIS FILE DOES NOT DO. It does not produce a "last checked" date. A check
 * is a person opening the source and re-reading it, which git cannot observe.
 * Pages that genuinely have one pass it explicitly, sourced from a partner data
 * file's readOn. Everything else says "Last updated", which is what git knows.
 *
 * THE COMMITTED FILE IS THE SOURCE OF TRUTH. This script UPDATES it; it never
 * replaces it wholesale. `vercel deploy` from the CLI uploads a source tarball
 * with no .git, so every git call returns "fatal: not a git repository". The
 * first version of this script wrote an empty map in that case, every
 * "Last updated" line rendered blank, and the build then failed three checks
 * later in check-price-provenance, whose message said nothing about dates being
 * missing. Every CLI deploy failed that way while the Git-integration build,
 * which does have the repo, succeeded and served production. The site looked
 * fine and half the deploys were red.
 *
 * So: read the existing file, overlay whatever git can answer, and keep the rest.
 * If git answers nothing at all, keep the committed data and say so loudly.
 *
 * Run: npm run gen:dates   (also run by prebuild)
 */
import { execSync } from "node:child_process";
import { readdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const APP = "src/app";
const OUT = "src/lib/page-dates.ts";

function pages(dir = APP, acc = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) pages(p, acc);
    else if (e.name === "page.tsx") acc.push(p);
  }
  return acc;
}

const git = (args) => execSync(`git ${args}`, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();

/** Whatever is already committed. Anything git cannot answer keeps this value. */
function existing() {
  if (!existsSync(OUT)) return {};
  const m = readFileSync(OUT, "utf8").match(/PAGE_DATES: Record<string, PageDates> = (\{[\s\S]*?\n\});/);
  if (!m) return {};
  try {
    return JSON.parse(m[1]);
  } catch {
    return {};
  }
}

const entries = existing();
const before = Object.keys(entries).length;
let fromGit = 0;
for (const file of pages()) {
  const route = "/" + file.slice(APP.length + 1).replace(/\/page\.tsx$/, "").replace(/^page\.tsx$/, "");
  if (route.includes("[")) continue;
  const key = route === "/" ? "/" : route.replace(/\/$/, "");
  let published, updated;
  try {
    const adds = git(`log --diff-filter=A --format=%ad --date=short -- "${file}"`).split("\n").filter(Boolean);
    published = adds[adds.length - 1];
    updated = git(`log -1 --format=%ad --date=short -- "${file}"`);
  } catch {
    continue;
  }
  if (!published || !updated) continue; // git said nothing: keep whatever is committed
  entries[key] = { published, updated };
  fromGit++;
}

if (fromGit === 0) {
  console.warn(
    `\n  WARNING: git answered for 0 routes, so no date was refreshed.\n` +
      `  Keeping the ${before} committed entries. This is expected in a build with no\n` +
      `  .git (a 'vercel deploy' tarball) and is why this script updates rather than\n` +
      `  replaces. If you see this locally, your working copy has no git history and\n` +
      `  the dates on the site are as stale as the last commit of ${OUT}.\n`,
  );
  if (before === 0) {
    console.error(`  And ${OUT} is empty, so every page will render a blank date. Refusing to continue.`);
    process.exit(1);
  }
}

const body = `/**
 * GENERATED by scripts/generate-page-dates.mjs. Do not edit by hand.
 *
 * published = first commit that added the page's source
 * updated   = most recent commit that touched it
 *
 * Neither is a "last checked" date; git cannot see a person re-reading a
 * vendor's page. See the generator's header for why these are not props.
 */
export type PageDates = { published: string; updated: string };

export const PAGE_DATES: Record<string, PageDates> = ${JSON.stringify(entries, null, 2)};

export function pageDates(route: string): PageDates | undefined {
  return PAGE_DATES[route.replace(/\\/$/, "") || "/"];
}
`;
writeFileSync(OUT, body);
console.log(
  `  Wrote ${OUT}: ${Object.keys(entries).length} routes (${fromGit} refreshed from git, ` +
    `${Object.keys(entries).length - fromGit} kept from the committed file).`,
);
