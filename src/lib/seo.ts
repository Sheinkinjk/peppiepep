export interface SEOConfig {
  title: string;
  description: string;
  keywords?: string[];
  image?: string;
  url?: string;
  type?: "website" | "article";
  noIndex?: boolean;
}

const SITE_NAME = "Refer Labs";
export const SITE_URL = process.env.NEXT_PUBLIC_SITE_URL || "https://referlabs.com.au";
// Left undefined on purpose: x.com/referlabs 404s, and every page was declaring
// twitter:site and twitter:creator for a handle that does not exist. A dead
// handle is a worse entity signal than no handle, since it points a verifier at
// nothing. Set this the day the account is registered and both tags return.
/**
 * Shared references to the two entities every page's schema should point at.
 *
 * Both are `@id` references, never inlined copies: the Organization node is
 * defined once in StructuredData.tsx and the Person node once on the author
 * page, so a consumer resolving either gets one entity rather than fifty
 * near-duplicates that look like fifty different publishers.
 */
export const SCHEMA_PUBLISHER = { "@id": `${SITE_URL}/#organization` } as const;
export const SCHEMA_AUTHOR = { "@id": `${SITE_URL}/authors/jarred#person` } as const;

const TWITTER_HANDLE: string | undefined = undefined;

/** Per-page, branded Open Graph card generated by /og from the page title. */
function dynamicOgImage(title: string): string {
  return `${SITE_URL}/og?title=${encodeURIComponent(title)}`;
}

/**
 * Generate comprehensive metadata for SEO, Open Graph, and Twitter Cards
 */
export function generateMetadata(config: SEOConfig): Metadata {
  const {
    title,
    description,
    keywords = [],
    image,
    url,
    type = "website",
    noIndex = false,
  } = config;

  const fullTitle = title.includes(SITE_NAME) ? title : `${title} | ${SITE_NAME}`;
  const canonicalUrl = url || SITE_URL;
  // Each page gets a unique, branded OG card built from its title unless an
  // explicit image is supplied — lifts social/SERP click-through site-wide.
  const ogImage = image || dynamicOgImage(title);

  return {
    metadataBase: new URL(SITE_URL),
    title: fullTitle,
    description,
    // Meta keywords are ignored by Google/Bing and long lists read as low-effort
    // SEO; intentionally not emitted. Keyword arrays are kept in configs for our
    // own reference only.

    // Robots
    robots: noIndex
      ? {
          index: false,
          follow: false,
        }
      : {
          index: true,
          follow: true,
          googleBot: {
            index: true,
            follow: true,
            "max-video-preview": -1,
            "max-image-preview": "large",
            "max-snippet": -1,
          },
        },

    // Open Graph
    openGraph: {
      title: fullTitle,
      description,
      url: canonicalUrl,
      siteName: SITE_NAME,
      images: [
        {
          url: ogImage,
          width: 1200,
          height: 630,
          alt: title,
        },
      ],
      locale: "en_AU",
      type,
    },

    // Twitter Card
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: [ogImage],
      ...(TWITTER_HANDLE ? { creator: TWITTER_HANDLE, site: TWITTER_HANDLE } : {}),
    },

    // Additional meta tags
    alternates: {
      canonical: canonicalUrl,
    },

    // Verification tags
    //
    // Google is the only token emitted here, and that is not a gap. Bing
    // Webmaster Tools IS set up for referlabs.com.au and verified outside this
    // file (DNS / XML file / Search Console import), so there is nothing to add.
    // Its AI Performance report is read regularly: 1,200 citations over 28 days,
    // 201 pages indexed, 34 warnings, 15 excluded, with a full query breakdown.
    // A file-level audit sees `google` alone and concludes Bing is a blind spot.
    // It has been concluded wrongly at least once. Do not add a Bing token here
    // and do not treat Bing coverage as unknown; ask for the report instead.
    verification: {
      google: process.env.NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION,
    },

    // App-specific metadata
    applicationName: SITE_NAME,

    // Referrer policy
    referrer: "origin-when-cross-origin",

    // Category
    category: "Business Services",

    // Authors
    authors: [{ name: SITE_NAME }],

    // Creator
    creator: SITE_NAME,

    // Publisher
    publisher: SITE_NAME,

    // Format detection
    formatDetection: {
      email: false,
      address: false,
      telephone: false,
    },

    // Icons
    // logo.svg is the 128x96 wordmark. It was declared as both the favicon and the
    // apple-touch-icon, which are square formats, so it competed with favicon.ico
    // and iOS ignored it outright. Google was left resolving two rel="icon" tags
    // and served a plain black-and-white mark that is not the brand at all.
    // These are square, on-brand, and sized to Google's rule that a favicon be a
    // square multiple of 48.
    icons: {
      icon: [
        { url: "/favicon.ico", sizes: "48x48 96x96 144x144", type: "image/x-icon" },
        { url: "/icon-192.png", sizes: "192x192", type: "image/png" },
      ],
      apple: [{ url: "/apple-touch-icon.png", sizes: "180x180", type: "image/png" }],
    },

    // Manifest
    manifest: "/manifest.json",
  };
}

